from datetime import datetime
from typing import Optional, List, Dict, Any
from sqlalchemy.orm import Session
from backend.app.models.social import Post, ApprovalLog, Persona
from agent.graph.workflow import run_agent_generation, resume_agent_with_feedback

class PostService:

    @staticmethod
    def generate_post(
        db: Session,
        topic: str,
        tone: str = "engaging",
        target_platforms: List[str] = None,
        persona_id: Optional[str] = None,
        generate_thread: bool = False
    ) -> Post:
        """Invokes LangGraph agent to generate draft and stores as pending_approval."""
        persona_dna = None
        if persona_id:
            persona = db.query(Persona).filter(Persona.id == persona_id).first()
            if persona:
                persona_dna = {
                    "name": persona.name,
                    "archetype": persona.archetype,
                    "tone_attributes": persona.tone_attributes,
                    "banned_words": persona.banned_words,
                    "sample_hooks": persona.sample_hooks,
                    "target_audience": persona.target_audience
                }
        else:
            default_persona = db.query(Persona).filter(Persona.is_default == True).first()
            if default_persona:
                persona_dna = {
                    "name": default_persona.name,
                    "archetype": default_persona.archetype,
                    "tone_attributes": default_persona.tone_attributes,
                    "banned_words": default_persona.banned_words,
                    "sample_hooks": default_persona.sample_hooks,
                    "target_audience": default_persona.target_audience
                }

        agent_res = run_agent_generation(
            topic=topic,
            tone=tone,
            target_platforms=target_platforms or ["twitter", "linkedin"],
            persona_dna=persona_dna,
            generate_thread=generate_thread
        )
        
        thread_id = agent_res["thread_id"]
        state = agent_res["state"]

        post = Post(
            topic=topic,
            tone=tone,
            persona_id=persona_id,
            raw_content=state.get("raw_draft", ""),
            is_thread=generate_thread,
            thread_tweets=state.get("thread_tweets", []),
            carousel_slides=state.get("carousel_slides", []), 
            platform_content=state.get("platform_posts", {}),
            status="pending_approval",
            critique=state.get("critique", {}),
            thread_id=thread_id
        )
        db.add(post)
        db.flush()

        # Log creation
        log = ApprovalLog(
            post_id=post.id,
            action="created",
            reviewer_feedback="Initial draft generated by LangGraph Agent"
        )
        db.add(log)
        db.commit()
        db.refresh(post)
        return post

    @staticmethod
    def approve_post(
        db: Session,
        post_id: str,
        scheduled_for: Optional[datetime] = None
    ) -> Post:
        """Approves a post and schedules it for future publication or immediate release."""
        post = db.query(Post).filter(Post.id == post_id).first()
        if not post:
            raise ValueError(f"Post {post_id} not found")

        post.status = "scheduled" if scheduled_for else "approved"
        post.scheduled_for = scheduled_for

        log = ApprovalLog(
            post_id=post.id,
            action="approved",
            reviewer_feedback=f"Post approved. Schedule: {scheduled_for or 'Immediate'}"
        )
        db.add(log)
        db.commit()
        db.refresh(post)
        return post

    @staticmethod
    def reject_post_with_feedback(
        db: Session,
        post_id: str,
        feedback: str
    ) -> Post:
        """Rejects post and feeds feedback back into LangGraph to regenerate copy."""
        post = db.query(Post).filter(Post.id == post_id).first()
        if not post:
            raise ValueError(f"Post {post_id} not found")

        # Re-enter LangGraph feedback loop if thread exists
        if post.thread_id:
            revised = resume_agent_with_feedback(post.thread_id, feedback)
            new_state = revised["state"]
            post.raw_content = new_state.get("raw_draft", post.raw_content)
            post.platform_content = new_state.get("platform_posts", post.platform_content)
            post.critique = new_state.get("critique", post.critique)
        
        post.status = "pending_approval"  # Back in review queue with new draft!

        log = ApprovalLog(
            post_id=post.id,
            action="rejected",
            reviewer_feedback=feedback
        )
        db.add(log)
        db.commit()
        db.refresh(post)
        return post

    @staticmethod
    def edit_post(
        db: Session,
        post_id: str,
        platform_content: Dict[str, str]
    ) -> Post:
        """Human reviewer directly edits the copy before approving."""
        post = db.query(Post).filter(Post.id == post_id).first()
        if not post:
            raise ValueError(f"Post {post_id} not found")

        old_content = post.platform_content or {}
        post.platform_content = platform_content

        log = ApprovalLog(
            post_id=post.id,
            action="edited",
            reviewer_feedback="Direct copy edits applied by human reviewer",
            diff_content={"before": old_content, "after": platform_content}
        )
        db.add(log)
        db.commit()
        db.refresh(post)
        return post

    @staticmethod
    def get_post(db: Session, post_id: str) -> Optional[Post]:
        return db.query(Post).filter(Post.id == post_id).first()

    @staticmethod
    def get_pending_posts(db: Session) -> List[Post]:
        return db.query(Post).filter(Post.status == "pending_approval").order_by(Post.created_at.desc()).all()

    @staticmethod
    def list_posts(db: Session, status: Optional[str] = None) -> List[Post]:
        return PostService.get_all_posts(db=db, status=status)

    @staticmethod
    def get_all_posts(db: Session, status: Optional[str] = None) -> List[Post]:
        query = db.query(Post)
        if status:
            query = query.filter(Post.status == status)
        return query.order_by(Post.created_at.desc()).all()